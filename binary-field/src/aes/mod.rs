    /// Multiplication straight from the modulus, one coefficient of the multiplier at a time.
    ///
    /// The routine under test packs both folds into shifts of a whole byte.
    ///
    /// This loop shares none of that structure.
    fn schoolbook(a: u8, b: u8) -> u8 {
        let mut acc = 0u8;
        for i in (0..8).rev() {
            // Double, rewriting the overflow as the modulus tail.
            let overflowed = acc & 0x80 != 0;
            acc <<= 1;
            if overflowed {
                acc ^= 0x1b;
            }
            if (b >> i) & 1 == 1 {
                acc ^= a;
            }
        }
        acc
    }

    #[test]
    fn the_modulus_reduces_the_way_the_polynomial_says() {
        // x^7 * x = x^8 = x^4 + x^3 + x + 1, the tail spelled 0x1b.
        assert_eq!(mul_bytes(0x80, 0x02), 0x1b);

        // The worked example from the block cipher's own column mixing.
        assert_eq!(mul_bytes(0xd4, 0x02), 0xb3);
        assert_eq!(mul_bytes(0xbf, 0x03), 0xda);

        // Far below the modulus, so nothing folds at all.
        assert_eq!(mul_bytes(0x02, 0x04), 0x08);
    }

    #[test]
    fn the_published_substitution_box_entries_come_out() {
        // The cipher's substitution box is inversion followed by a fixed affine map.
        //
        // Its published entries therefore pin both the inverse and the map engine.
        //
        //     s(x) = A(x^254) + 0x63,   A the map with the circulant rows of 0x1f
        let affine = ByteMatrix::from_images([0x1f, 0x3e, 0x7c, 0xf8, 0xf1, 0xe3, 0xc7, 0x8f]);

        // The quadword published for the inverting affine-byte instruction's matrix operand.
        //
        // This pins the row layout to the hardware on every host, not only on those that run it.
        assert_eq!(affine.to_quadword(), 0xf1e3_c78f_1f3e_7cf8);

        let sbox = |x: u8| affine.apply(super::invert_byte(x)) ^ 0x63;

        // Entries 0x00, 0x01, 0x53 and 0xff of the published table.
        assert_eq!(sbox(0x00), 0x63);
        assert_eq!(sbox(0x01), 0x7c);
        assert_eq!(sbox(0x53), 0xed);
        assert_eq!(sbox(0xff), 0x16);
    }


/// The carryless product of a value with the modulus below its leading term.
///
/// That tail is `x^4 + x^3 + x + 1`, so its four set bits are the four shifts.
const fn fold_tail(v: u16) -> u16 {
    (v << 4) ^ (v << 3) ^ (v << 1) ^ v
}

/// The carryless product of two bytes, as a polynomial of degree at most fourteen.
const fn carryless(a: u8, b: u8) -> u16 {
    let a = a as u16;
    let mut acc = 0u16;
    let mut i = 0;
    while i < 8 {
        // All ones when bit `i` of the second operand is set, all zeros otherwise.
        let selected = 0u16.wrapping_sub(((b >> i) & 1) as u16);
        acc ^= (a << i) & selected;
        i += 1;
    }
    acc
}

/// The product of two elements, as bytes.
///
/// The modulus rewrites `x^8` as a tail of degree 4, so the high half folds down by that tail.
///
/// That fold reaches degree `6 + 4`, spilling three bits back over the top.
///
/// A second fold of those lands at degree `2 + 4`, below the top, so two rounds are exact.
#[inline]
pub(crate) const fn mul_bytes(a: u8, b: u8) -> u8 {
    let product = carryless(a, b);

    // The half above the modulus, rewritten by the tail.
    let folded = fold_tail(product >> 8);

    // What that fold pushed back over the top, rewritten once more.
    (product ^ folded ^ fold_tail(folded >> 8)) as u8
}

/// The inverse of an element, with zero left alone.
///
/// The multiplicative group has order 255, so inversion is the map raising to the power 254.
///
/// Zero is outside that group, and the same power sends it to itself.
///
/// That is also the convention the byte-wise hardware inverse follows.
///
/// # Algorithm
///
/// An addition chain on the exponent, eleven products of which seven are squarings:
///
/// ```text
///     1, 2, 3, 6, 12, 15, 30, 60, 120, 240, 252, 254
/// ```
#[inline]
pub(crate) const fn invert_byte(a: u8) -> u8 {
    let x2 = mul_bytes(a, a);
    let x3 = mul_bytes(x2, a);
    let x6 = mul_bytes(x3, x3);
    let x12 = mul_bytes(x6, x6);
    let x15 = mul_bytes(x12, x3);
    let x30 = mul_bytes(x15, x15);
    let x60 = mul_bytes(x30, x30);
    let x120 = mul_bytes(x60, x60);
    let x240 = mul_bytes(x120, x120);
    let x252 = mul_bytes(x240, x12);
    mul_bytes(x252, x2)
}

/// The images of the tower generators here, as the smallest solution at each level.
///
/// The tower is generated by elements obeying `X_k^2 + X_{k-1} X_k + 1 = 0`, with `X_-1 = 1`.
///
/// Any images obeying those same relations extend to a homomorphism of `F_2`-algebras.
///
/// Both sides are fields of the same size, so that homomorphism is an isomorphism.
const XI: [u8; 3] = {
    let mut xi = [0u8; 3];
    let mut k = 0;
    while k < 3 {
        let previous = if k == 0 { 1 } else { xi[k - 1] };
        let mut candidate = 1u16;
        while candidate < 256 {
            let c = candidate as u8;
            if mul_bytes(c, c) ^ mul_bytes(previous, c) ^ 1 == 0 {
                xi[k] = c;
                break;
            }
            candidate += 1;
        }
        assert!(xi[k] != 0, "the tower relations have no solution here");
        k += 1;
    }
    xi
};

/// The bit pattern of the multiplicative generator of the tower representation.
///
/// Its image here is the generator, so the change of basis carries one onto the other.
const TOWER_GENERATOR: u8 = 0x13;

/// The map out of the tower basis, column by column.
///
/// The tower basis vector indexed by a bit pattern is the product of the generators it names.
///
/// Stripping the lowest set bit reuses the image already computed for the rest.
const fn tower_images() -> [u8; 8] {
    let mut images = [0u8; 8];
    images[0] = 1;
    let mut j = 1usize;
    while j < 8 {
        let lowest = j.trailing_zeros() as usize;
        images[j] = mul_bytes(XI[lowest], images[j & (j - 1)]);
        j += 1;
    }
    images
}

/// Where each basis vector of the tower representation lands here.
const FROM_TOWER: ByteMatrix = ByteMatrix::from_images(tower_images());

/// Where each basis vector here lands in the tower representation.
///
/// An injective map on a byte is a permutation of the 256 values.
///
/// Searching for the preimage of each basis vector therefore recovers the inverse.
const INTO_TOWER: ByteMatrix = {
    let mut images = [0u8; 8];
    let mut b = 0;
    while b < 8 {
        let target = 1u8 << b;
        let mut x = 1u16;
        while x < 256 {
            if FROM_TOWER.apply(x as u8) == target {
                images[b] = x as u8;
                break;
            }
            x += 1;
        }
        b += 1;
    }
    ByteMatrix::from_images(images)
};

// Composing the two directions must leave every byte alone.
//
// That rules out both a wrong preimage search and a change of basis that is not invertible.
const _: () = assert!(
    INTO_TOWER.compose(FROM_TOWER).to_quadword() == ByteMatrix::IDENTITY.to_quadword(),
    "the change of basis is not invertible"
);

/// The Cantor basis in this representation, carried over from the tower's own.
///
/// Both representations then span the same additive transform domain.
const CANTOR_BASIS: [u8; 8] = {
    let mut basis = [0u8; 8];
    let mut i = 0;
    while i < 8 {
        basis[i] = FROM_TOWER.apply(CANTOR_BASIS_128[i] as u8);
        i += 1;
    }
    basis
};

/// The binary field `GF(2^8)` modulo `x^8 + x^4 + x^3 + x + 1`.
///
/// Bit `i` stores the coefficient of `x^i`, and every byte is a distinct field element.
///
/// This is the modulus the byte-wise field instructions are defined for.
///
/// That is what makes it worth carrying beside the tower's own byte field.
///
/// Arithmetic here is table-free: nothing indexes a table by an operand.
#[derive(Copy, Clone, Default, PartialEq, Eq, Hash, PartialOrd, Ord, Serialize, Deserialize)]
#[serde(transparent)]
#[repr(transparent)]
#[must_use]
pub struct Rijndael8b(u8);

impl Rijndael8b {
    /// The number of bits of an element.
    pub(crate) const BITS: usize = 8;

    /// Construct a field element from its byte representation.
    ///
    /// Every byte is a valid element.
    #[inline]
    pub const fn from_byte(byte: u8) -> Self {
        Self(byte)
    }

    /// The byte representation of this element.
    #[must_use]
    #[inline]
    pub const fn to_byte(self) -> u8 {
        self.0
    }

    /// The inverse of this element, with zero sent to zero.
    ///
    /// The chain runs whatever the operand is, so its cost says nothing about the value.
    #[inline]
    pub const fn invert_or_zero(self) -> Self {
        Self(invert_byte(self.0))
    }

    /// Multiplication by this element, as a map ready for the byte-wise engine.
    ///
    /// Scaling is `F_2`-linear, so a fixed factor is a matrix like any other.
    pub const fn scaling_matrix(self) -> ByteMatrix {
        let mut images = [0u8; 8];
        let mut b = 0;
        while b < 8 {
            images[b] = mul_bytes(self.0, 1 << b);
            b += 1;
        }
        ByteMatrix::from_images(images)
    }
}


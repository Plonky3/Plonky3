/// Batch sizes that reach every pass of every backend.
///
/// - 1 and 3 stay below a four-stream group.
/// - 9 and 20 end on one AVX-512 register group.
/// - 32 is one full AVX-512 pass, and 40 leaves eight messages after it.
pub(crate) const COUNTS: [usize; 6] = [1, 3, 9, 20, 32, 40];

#[test]
fn hash_many_matches_every_cavp_vector_in_every_batch_shape() {
    use alloc::vec;

    use p3_symmetric::CryptographicHasher;

    use crate::Sha256;

    for (message, expected) in SHORT_MSG.iter().chain(LONG_MSG) {
        for count in COUNTS {
            // The same message in every lane, so each lane must give the vector's digest.
            let input = message.repeat(count);
            let mut out = vec![[0u8; 32]; count];
            Sha256.hash_many(&input, &mut out);

            assert!(
                out.iter().all(|digest| digest == expected),
                "{} bytes, {count} copies",
                message.len()
            );
        }
    }
}
